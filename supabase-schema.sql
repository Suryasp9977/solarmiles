create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  email text,
  pincode text,
  bill numeric,
  bill_range text,
  system_kw numeric,
  estimated_savings numeric,
  area numeric,
  location text,
  roof text,
  property text,
  source text default 'website',
  created_at timestamptz default now()
);

-- Google Sheet sync status. sheet_synced_at = null means "not in the sheet yet".
alter table public.leads add column if not exists sheet_synced_at timestamptz;
alter table public.leads add column if not exists sheet_last_error text;

create index if not exists leads_created_at_idx on public.leads(created_at desc);
create index if not exists leads_unsynced_idx on public.leads(created_at) where sheet_synced_at is null;

-- Row Level Security. The public key may only INSERT valid, not-yet-synced leads,
-- so visitors cannot mark leads as synced or read anything.
alter table public.leads enable row level security;

drop policy if exists "public can submit leads" on public.leads;
create policy "public can submit leads" on public.leads
  for insert
  to anon
  with check (
    char_length(name) between 2 and 120
    and phone ~ '^[0-9]{10}$'
    and (email is null or char_length(email) <= 160)
    and (pincode is null or pincode ~ '^[0-9]{6}$')
    and sheet_synced_at is null
    and sheet_last_error is null
  );